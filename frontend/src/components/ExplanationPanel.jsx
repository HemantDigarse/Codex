import { useState } from 'react';
import toast from 'react-hot-toast';
import {
  FileText,
  ListOrdered,
  Variable,
  Terminal,
  Clock,
  HardDrive,
  AlertTriangle,
  Copy,
  Check,
} from 'lucide-react';

/**
 * Card wrapper for each explanation section.
 */
function SectionCard({ icon: Icon, title, iconColor, children }) {
  return (
    <div className="glass-card p-5 animate-fade-in">
      <div className="flex items-center gap-2.5 mb-3">
        <div className={`w-8 h-8 rounded-lg flex items-center justify-center ${iconColor}`}>
          <Icon className="w-4 h-4 text-white" />
        </div>
        <h3 className="text-base font-semibold text-white">{title}</h3>
      </div>
      <div className="text-sm text-gray-300 leading-relaxed whitespace-pre-wrap">
        {children}
      </div>
    </div>
  );
}

/**
 * Renders the structured AI explanation in a card-based layout.
 */
function ExplanationPanel({ data }) {
  const [copied, setCopied] = useState(false);

  if (!data) return null;

  const handleCopy = async () => {
    const text = buildPlainText(data);
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      toast.success('Explanation copied!');
      setTimeout(() => setCopied(false), 2000);
    } catch {
      toast.error('Failed to copy.');
    }
  };

  return (
    <div className="mt-10 animate-slide-up">
      {/* Section Header */}
      <div className="flex items-center justify-between mb-6">
        <div>
          <h2 className="text-xl font-bold text-white">Explanation</h2>
          <p className="text-sm text-gray-500 mt-0.5">
            Generated by AI — review carefully
          </p>
        </div>
        <button
          id="copy-explanation-btn"
          onClick={handleCopy}
          className="flex items-center gap-2 px-4 py-2 rounded-xl bg-dark-700 border border-dark-500 text-sm font-medium text-gray-300 hover:text-white hover:border-indigo-500/30 transition-all duration-200"
        >
          {copied ? (
            <Check className="w-4 h-4 text-green-400" />
          ) : (
            <Copy className="w-4 h-4" />
          )}
          {copied ? 'Copied!' : 'Copy Explanation'}
        </button>
      </div>

      {/* Cards */}
      <div className="grid gap-4">
        {data.summary && (
          <SectionCard
            icon={FileText}
            title="Code Summary"
            iconColor="bg-indigo-500/20"
          >
            {data.summary}
          </SectionCard>
        )}

        {data.explanation && (
          <SectionCard
            icon={ListOrdered}
            title="Step-by-Step Explanation"
            iconColor="bg-purple-500/20"
          >
            {data.explanation}
          </SectionCard>
        )}

        {data.importantElements && (
          <SectionCard
            icon={Variable}
            title="Important Variables & Functions"
            iconColor="bg-cyan-500/20"
          >
            {data.importantElements}
          </SectionCard>
        )}

        {data.expectedOutput && (
          <SectionCard
            icon={Terminal}
            title="Expected Output"
            iconColor="bg-green-500/20"
          >
            <div className="code-block p-3 mt-1">{data.expectedOutput}</div>
          </SectionCard>
        )}

        {data.timeComplexity && (
          <SectionCard
            icon={Clock}
            title="Time Complexity"
            iconColor="bg-amber-500/20"
          >
            {data.timeComplexity}
          </SectionCard>
        )}

        {data.spaceComplexity && (
          <SectionCard
            icon={HardDrive}
            title="Space Complexity"
            iconColor="bg-rose-500/20"
          >
            {data.spaceComplexity}
          </SectionCard>
        )}

        {data.potentialIssues && (
          <SectionCard
            icon={AlertTriangle}
            title="Potential Bugs & Issues"
            iconColor="bg-orange-500/20"
          >
            {data.potentialIssues}
          </SectionCard>
        )}
      </div>
    </div>
  );
}

/**
 * Builds a plain-text version for clipboard copying.
 */
function buildPlainText(data) {
  const sections = [];
  if (data.summary) sections.push(`## Code Summary\n${data.summary}`);
  if (data.explanation) sections.push(`## Step-by-Step Explanation\n${data.explanation}`);
  if (data.importantElements) sections.push(`## Important Variables & Functions\n${data.importantElements}`);
  if (data.expectedOutput) sections.push(`## Expected Output\n${data.expectedOutput}`);
  if (data.timeComplexity) sections.push(`## Time Complexity\n${data.timeComplexity}`);
  if (data.spaceComplexity) sections.push(`## Space Complexity\n${data.spaceComplexity}`);
  if (data.potentialIssues) sections.push(`## Potential Bugs & Issues\n${data.potentialIssues}`);
  return sections.join('\n\n');
}

export default ExplanationPanel;
